// Primitive Data Types (7/8).

console.log("DataTypes in JS");

// Data Types: Number
let age = 19;
console.log(age);

// Data Types: String
let name = "Divyam Lathiya";
console.log(name);

// Data Types: Boolean
let isKnow = true;
console.log(isKnow);

// Data Types: Undefined
let a;
console.log(a);

// Data Types: Null
let b = null;
console.log(b);

// Data Types: BigInt
let mobileNumber = BigInt("2611113642");
console.log(mobileNumber);

// Data Types: Symbol
let z = Symbol("Hello!");
console.log(z);



